const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/xiaohao/AppData/Local/npm-cache/_npx/e41f203b7505f1fb/node_modules/playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  const page = await browser.newPage({ viewport: { width: 1100, height: 800 } });
  page.setDefaultTimeout(5000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('file:///' + path.join(__dirname, 'index.html').replaceAll('\\', '/'));
  await page.waitForFunction(() => window.ready);
  await page.getByRole('button', { name: '运行结果', exact: true }).click();
  await page.locator('.controls-summary').click();
  await page.evaluate(async () => {
    const w = window, config = w.test.tasks.snapshot(), base = config.tasks[0];
    config.presets[0].raw.prompts = [{ identifier: 'chatHistory', name: 'history', role: 'system', marker: true }];
    config.presets[0].raw.prompt_order = [{ character_id: 100001, order: [{ identifier: 'chatHistory', enabled: true }] }];
    config.tasks = [base,
      { ...base, id: 'event-task', name: '禁常规的事件任务', enabled: false, eventName: 'frontend:event', output: { mode: 'event_result' } },
      { ...base, id: 'negative-task', name: '负序任务', order: -1, triggerInterval: 20 },
    ];
    config.groups[0].taskIds = config.tasks.map(task => task.id);
    await w.test.tasks.replaceSettings(config);
  });
  await page.getByRole('combobox', { name: '运行范围', exact: true }).selectOption('event');
  await page.getByRole('combobox', { name: '测试事件', exact: true }).selectOption('frontend:event');
  assert.match(await page.locator('.run-context').innerText(), /广播/);
  await page.getByRole('button', { name: '测试此事件', exact: true }).click();
  await page.waitForFunction(() => window.test.taskRunResults.value.length === 1);
  const first = await page.evaluate(() => ({ results: window.test.taskRunResults.value, events: window.events, chat: window.chat, variables: window.chatVariables, calls: window.httpCalls }));
  assert.equal(first.results[0].status, 'succeeded', JSON.stringify(first.results));
  assert.equal(first.results[0].tasks[0].taskId, 'event-task');
  assert.equal(first.results[0].tasks[0].text, '共享事件完整响应');
  assert.deepEqual(first.results[0].tasks[0].writes, []);
  assert.equal(first.events.filter(event => event[0] === 'frontend:event:result').length, 1);
  assert.equal(first.chat[0].mes, '助手正文');
  assert.deepEqual(Object.keys(first.variables), ['kat_async_task_state:full-ui-acceptance']);
  await page.locator('.integration-rules summary').click();
  await page.getByRole('button', { name: '一键复制前端联动规则', exact: true }).click();
  const copied = await page.evaluate(() => window.clipboardText);
  for (const text of ['frontend:event', 'waitGlobalInitialized', 'requestId', 'eventOn', 'tasks', 'text']) assert(copied.includes(text), text);
  assert(!copied.includes('kat_async_event_results'), 'copy rules must have no removed persistence key');
  await page.getByRole('combobox', { name: '运行范围', exact: true }).selectOption('task');
  await page.getByRole('combobox', { name: '测试任务', exact: true }).selectOption('negative-task');
  await page.getByRole('button', { name: '测试此任务', exact: true }).click();
  await page.waitForFunction(() => window.test.taskRunResults.value.length === 2);
  const negative = await page.evaluate(() => window.test.taskRunResults.value.at(-1));
  assert.equal(negative.status, 'succeeded');
  assert.deepEqual(negative.tasks.map(task => task.taskId), ['negative-task']);
  await page.getByRole('combobox', { name: '测试任务', exact: true }).selectOption('event-task');
  await page.getByRole('button', { name: '测试此任务', exact: true }).click();
  await page.waitForFunction(() => window.test.taskRunResults.value.length === 3);
  const single = await page.evaluate(() => window.test.taskRunResults.value.at(-1));
  assert.equal(single.status, 'succeeded'); assert.equal(single.trigger.kind, 'event');
  assert.deepEqual(single.tasks.map(task => task.taskId), ['event-task']);
  await page.screenshot({ path: path.join(__dirname, 'event-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 375, height: 800 });
  assert(await page.getByRole('combobox', { name: '运行范围', exact: true }).isVisible());
  assert(await page.getByRole('button', { name: '测试此任务', exact: true }).isVisible());
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
  assert(!overflow, 'mobile page must not overflow horizontally');
  await page.screenshot({ path: path.join(__dirname, 'event-mobile.png'), fullPage: true });
  await page.locator('.mobile-navigation select').selectOption({ label: '任务' });
  await page.locator('.task-row').filter({ hasText: '禁常规的事件任务' }).getByRole('button', { name: '编辑', exact: true }).click();
  const editor = page.locator('.task-editor-modal');
  await editor.waitFor();
  const enabled = editor.locator('[data-config-key="enabled"]');
  assert.equal(await enabled.isChecked(), false);
  const tip = enabled.locator('..').getByRole('button', { name: '查看字段说明' });
  await tip.hover();
  await page.getByRole('tooltip').waitFor();
  assert.match(await page.getByRole('tooltip').innerText(), /即使关闭此开关/);
  const checkTipGeometry = async () => {
    const measured = await page.getByRole('tooltip').evaluate(node => {
      const r = node.getBoundingClientRect();
      return { x: r.x, y: r.y, right: r.right, bottom: r.bottom, width: innerWidth, height: innerHeight, topLevel: node.parentElement === document.body };
    });
    assert(measured.topLevel, 'tooltip must escape the modal overflow container');
    assert(measured.x >= 0 && measured.y >= 0 && measured.right <= measured.width && measured.bottom <= measured.height, JSON.stringify(measured));
  };
  await checkTipGeometry();
  await tip.dispatchEvent('mouseleave');
  await tip.focus();
  await page.getByRole('tooltip').waitFor();
  assert.equal(await tip.getAttribute('aria-expanded'), 'true');
  assert.equal(await tip.getAttribute('aria-describedby'), await page.getByRole('tooltip').getAttribute('id'));
  await tip.press('Escape');
  assert.equal(await page.getByRole('tooltip').count(), 0);
  await tip.click();
  await page.getByRole('tooltip').waitFor();
  assert.equal(await enabled.isChecked(), false, 'tooltip click must not toggle the associated checkbox');
  await checkTipGeometry();
  await page.screenshot({ path: path.join(__dirname, 'tooltip-mobile.png'), fullPage: true });
  await tip.press('Escape');
  await editor.getByText('触发与高级参数', { exact: true }).click();
  const intervalTip = editor.locator('[data-config-key="triggerInterval"]').locator('..').getByRole('button', { name: '查看字段说明' });
  await intervalTip.click();
  await page.getByRole('tooltip').waitFor();
  assert.match(await page.getByRole('tooltip').innerText(), /仅间隔大于 1.*1 表示不限制/);
  await checkTipGeometry();
  await page.setViewportSize({ width: 1100, height: 800 });
  await intervalTip.hover();
  await page.getByRole('tooltip').waitFor();
  await checkTipGeometry();
  await page.screenshot({ path: path.join(__dirname, 'tooltip-desktop.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS production App event/negative-order/single-task execution, broadcast/no result persistence, copy integration rules, desktop/mobile layout and tooltip hover/focus/click/Escape/checkbox/viewport geometry');
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
